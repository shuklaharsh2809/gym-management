import { Bell } from "lucide-react";
import type { Metadata } from "next";
import Link from "next/link";
import { EmptyState } from "@/components/shared/empty-state";
import { PageHeader } from "@/components/shared/page-header";
import { Card } from "@/components/ui/card";
import { formatDateTime } from "@/lib/formatters";
import { listMyNotifications } from "@/modules/notifications/service";
import { requireOrganizationContext } from "@/server/auth/session";
import { db } from "@/server/database/client";

export const metadata: Metadata = { title: "Notifications" };

export default async function NotificationsPage() {
  const ctx = await requireOrganizationContext();
  const { items } = await listMyNotifications(db, ctx, 100);
  const { locale, timezone } = ctx.organization;
  return (
    <>
      <PageHeader
        title="Notifications"
        description="Reminders and alerts generated by FitGrid's daily checks."
      />
      <Card>
        {items.length === 0 ? (
          <EmptyState icon={Bell} title="No notifications" />
        ) : (
          <ul className="divide-y divide-border">
            {items.map((n) => (
              <li key={n.id} className="flex items-start justify-between gap-4 px-5 py-3 text-sm">
                <div>
                  <p className={n.readAt ? "text-muted-foreground" : "font-medium"}>
                    {n.link ? (
                      <Link href={n.link} className="hover:underline">
                        {n.title}
                      </Link>
                    ) : (
                      n.title
                    )}
                  </p>
                  {n.body && <p className="text-muted-foreground">{n.body}</p>}
                </div>
                <span className="shrink-0 text-xs text-muted-foreground">
                  {formatDateTime(n.createdAt, locale, timezone)}
                </span>
              </li>
            ))}
          </ul>
        )}
      </Card>
    </>
  );
}
